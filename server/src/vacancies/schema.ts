import type { JsonSchema } from '../llm/types.js';
import { validateOutput } from '../llm/validate.js';
import type { Migration } from '../data/migrate.js';
import { PROVIDER_IDS, SUPPORTED_LANGUAGES } from '../data/settings.js';
import { isAaHost, jobdetailUrl } from './aa-links.js';

export const VACANCIES_SCHEMA_VERSION = 4;

/** migrations[n] turns vacancies.json version n into n + 1 (applied on read; written back on the next save). */
export const VACANCY_MIGRATIONS: Readonly<Record<number, Migration>> = {
  // 2: a score says which AI wrote it (Claude was the only AI before 0.8.0).
  // A malformed file (vacancies not a list, a card not an object) is passed through unchanged, so validation fails
  // and the store sets the file aside instead of emptying it.
  1: (doc) => Array.isArray(doc.vacancies)
    ? {
      ...doc,
      vacancies: doc.vacancies.map((v: unknown) => {
        if (!v || typeof v !== 'object') return v;
        const x = v as Record<string, unknown>;
        return x.score && typeof x.score === 'object' ? { ...x, score: { ...(x.score as object), provider: 'claude' } } : x;
      }),
    }
    : doc,
  // 3: a score says which language its points are written in (not recorded before 0.8.2).
  2: (doc) => Array.isArray(doc.vacancies)
    ? {
      ...doc,
      vacancies: doc.vacancies.map((v: unknown) => {
        if (!v || typeof v !== 'object') return v;
        const x = v as Record<string, unknown>;
        return x.score && typeof x.score === 'object' ? { ...x, score: { ...(x.score as object), language: null } } : x;
      }),
    }
    : doc,
  // 4 (0.9.1): the contact gets phone and address; an Arbeitsagentur card always links to its offer page — the old
  // code replaced the link with the API's partner link, which is often just the Arbeitsagentur home page.
  3: (doc) => Array.isArray(doc.vacancies)
    ? {
      ...doc,
      vacancies: doc.vacancies.map((v: unknown) => {
        if (!v || typeof v !== 'object') return v;
        const x = { ...(v as Record<string, unknown>) };
        if (x.contact && typeof x.contact === 'object') x.contact = withContactFields(x.contact as Record<string, unknown>);
        if (x.source === 'arbeitsagentur' && typeof x.sourceId === 'string' && x.sourceId && typeof x.url === 'string') {
          const offer = jobdetailUrl(x.sourceId);
          if (x.url !== offer) {
            if (x.url && !isAaHost(x.url)) x.partnerUrl = x.url;
            x.url = offer;
          }
        }
        return x;
      }),
    }
    : doc,
};

/** Contact fields added in 0.9.1; old contacts get them empty (shared with the package migration). */
export function withContactFields(c: Record<string, unknown>): Record<string, unknown> {
  return { phone: '', street: '', postcode: '', city: '', ...c };
}
export const VACANCY_LIMITS = {
  title: 300, company: 300, location: 100, locations: 20, point: 300, points: 3, salary: 200, url: 2000, email: 300, name: 200,
  sourceId: 64, text: 100_000, phone: 40, street: 120, postcode: 10, city: 80,
} as const;
/** Ids are generated by the server; the check also keeps text file names inside texts/. */
export const VACANCY_ID = /^[A-Za-z0-9_-]{1,64}$/;

const L = VACANCY_LIMITS;
const str = (maxLength: number): JsonSchema => ({ type: 'string', maxLength });
const TIMESTAMP = str(40);
const nullable = (s: JsonSchema): JsonSchema => ({ anyOf: [s, { type: 'null' }] });
/** `optional`: fields older files may lack (not in `required`). */
function obj(properties: Record<string, JsonSchema>, optional: Record<string, JsonSchema> = {}): JsonSchema {
  return { type: 'object', additionalProperties: false, required: Object.keys(properties), properties: { ...properties, ...optional } };
}
const points = { type: 'array', maxItems: L.points, items: str(L.point) };
const URL_FIELD: JsonSchema = { type: 'string', maxLength: L.url, pattern: '^(https?://.+)?$' };
/** The employer contact of a card — the package copies it with the same schema. */
export const CONTACT: JsonSchema = obj({
  email: str(L.email), salutation: { enum: ['', 'Frau', 'Herr'] }, name: str(L.name),
  phone: str(L.phone), street: str(L.street), postcode: str(L.postcode), city: str(L.city),
});
/** Request body of PUT …/contact (vacancy and package): the contact the person saves; null = no contact. */
export const CONTACT_BODY: JsonSchema = { anyOf: [{ type: 'null' }, CONTACT] };

const VACANCY = obj({
  id: { type: 'string', pattern: VACANCY_ID.source },
  source: { enum: ['arbeitsagentur', 'manual'] },
  sourceId: nullable(str(L.sourceId)),
  addedManually: { type: 'boolean' },
  title: str(L.title),
  company: str(L.company),
  locations: { type: 'array', maxItems: L.locations, items: str(L.location) },
  remote: { enum: ['yes', 'partial', 'no', 'unknown'] },
  employment: { type: 'array', uniqueItems: true, items: { enum: ['fulltime', 'parttime', 'minijob', 'apprenticeship', 'internship'] } },
  salaryText: str(L.salary),
  publishedAt: { type: 'string', pattern: '^(\\d{4}-\\d{2}-\\d{2})?$' },
  foundAt: TIMESTAMP,
  url: { type: 'string', maxLength: L.url, pattern: '^(https?://.+)?$' },
  contact: nullable(CONTACT),
  hasText: { type: 'boolean' },
  status: { enum: ['new', 'favorite', 'hidden', 'stale'] },
  scoreState: { enum: ['pending', 'scored', 'failed', 'notScored'] },
  score: nullable(obj({ value: { type: 'integer', minimum: 0, maximum: 100 }, why: points, missing: points, scoredAt: TIMESTAMP, provider: { enum: [...PROVIDER_IDS] }, language: nullable({ enum: [...SUPPORTED_LANGUAGES] }) })),
  hiddenAt: nullable(TIMESTAMP),
}, {
  // 0.9.0: cards from before have no `initiative` (= false), so no migration is needed.
  initiative: { type: 'boolean' },
  // 0.9.1: only Arbeitsagentur cards with a partner page have it.
  partnerUrl: URL_FIELD,
});

const FILE = obj({ schemaVersion: { const: VACANCIES_SCHEMA_VERSION }, vacancies: { type: 'array', items: VACANCY } });

/** null = valid; otherwise a readable reason (for the log). */
export function validateVacancies(doc: unknown): string | null {
  const r = validateOutput(FILE, doc);
  if (!r.ok) return r.errors;
  const list = (doc as { vacancies: { id: string }[] }).vacancies;
  return new Set(list.map((v) => v.id)).size === list.length ? null : 'duplicate vacancy ids';
}
